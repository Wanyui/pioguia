// Generates src/icons/index.ts from lucide-static, inlining only the icons the site uses.
// Run with `npm run icons` after changing ICONS. The output is committed so builds need no network.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const ICONS = [
  // Categories (see src/lib/categories.ts)
  "mountain-snow", "ferris-wheel", "shopping-bag", "landmark", "concierge-bell", "utensils",
  // Interface
  "search", "sliders-horizontal", "locate-fixed", "layers", "list", "map", "phone", "navigation",
  "globe", "mail", "x", "chevron-right", "chevron-down", "share-2", "info", "map-pin",
];

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("lucide-static/package.json"));
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

const toKey = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const entries = ICONS.map((name) => {
  const svg = readFileSync(join(pkgDir, "icons", `${name}.svg`), "utf8");
  const inner = svg.replace(/<!--[\s\S]*?-->/, "").match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1];
  const body = inner.replace(/\s*\n\s*/g, "").trim();
  return `  ${JSON.stringify(toKey(name))}: ${JSON.stringify(body)},`;
});

const out = `// Generated by tools/build-icons.mjs from lucide-static@${version} (ISC license). Do not edit.
export const ICON_PATHS = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof ICON_PATHS;

/** Inline SVG markup for an icon; decorative (aria-hidden) unless a label is given. */
export const icon = (name: IconName, className = "icon", label?: string) =>
  \`<svg class="\${className}" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" \${
    label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true"'
  }>\${ICON_PATHS[name]}</svg>\`;
`;

mkdirSync(new URL("../src/icons/", import.meta.url), { recursive: true });
writeFileSync(new URL("../src/icons/index.ts", import.meta.url), out);
console.log(`src/icons/index.ts: ${ICONS.length} icons from lucide-static@${version}`);
